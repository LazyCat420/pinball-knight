/// Rotates a 3x5 bitmap by 180 degrees by reading cells in reverse order.
pub fn rotate_180_3x5(b: &[u8; 15]) -> [u8; 15] {
    let mut out = [0u8; 15];
    for i in 0..15 {
        out[i] = b[14 - i];
    }
    out
}

