#!/usr/bin/env node
/**
 * Generate a PERTURBABLE copy of a painter, for the synthetic-dataset work.
 *
 * A painter's design lives in module-scope `const`s — three colour ramps and a
 * dozen geometry numbers. This rewrites them to `let` and appends a `__perturb`
 * hook, so a sweep can reassign them between renders. The painter reads them
 * inside its frame functions, i.e. at CALL time, so reassigning and then calling
 * `make<Name>Paints()` yields a genuinely different creature.
 *
 * The output is DERIVED and gitignored: it would rot the moment the painter
 * moves. Regenerate rather than edit.
 *
 *   node scripts/make-perturbable.mjs jester
 *   node scripts/painter-diversity.entry.ts   # the yardstick
 *   node scripts/painter-sweep.entry.ts       # the sweep
 */
import { readFileSync, writeFileSync } from "node:fs";

const name = process.argv[2] ?? "jester";
const src = `src/game/pinball-knight/render/monsters/${name}.ts`;
const dst = `src/game/pinball-knight/render/monsters/${name}.perturb.ts`;

/**
 * Which knobs are SHAPE and which are PAINT.
 *
 * The split is the experiment: colour is the negative control and must move the
 * silhouette by exactly zero, and it does (0.000 over 200 samples). Anything
 * else would mean the distance metric is picking up something other than shape.
 */
const GROUPS = {
  jester: {
    geom: ["HIP_Y", "RUFF_Y", "HEAD_Y", "HEAD_R", "CROWN_Y", "COIL_W", "PLATE_R",
           "SPRING_IDLE", "SPRING_WALK", "SPRING_LOAD", "SPRING_FIRE"],
    colour: ["R_RED", "R_GOLD", "R_BONE_W", "R_SHOE", "R_RIM", "PAINT", "NOSE", "STAR"],
  },
};

const g = GROUPS[name];
if (!g) {
  console.error(`no knob groups for "${name}" — add them to GROUPS in this file.`);
  console.error(`candidates:\n` + (readFileSync(src, "utf8").match(/^const [A-Z_0-9]+.*$/gm) ?? []).join("\n"));
  process.exit(1);
}

let s = readFileSync(src, "utf8");
const all = [...g.geom, ...g.colour];
let n = 0;
for (const k of all) {
  const re = new RegExp(`^const ${k}(\\b[^=]*)=`, "m");
  if (re.test(s)) { s = s.replace(re, `let ${k}$1=`); n++; }
  else console.warn(`  MISS: ${k} (renamed or removed?)`);
}
if (n !== all.length) {
  console.error(`only ${n}/${all.length} knobs found — the painter moved; fix GROUPS before trusting a sweep.`);
  process.exit(1);
}

s += `

// ── PERTURBATION HOOK — GENERATED by scripts/make-perturbable.mjs, do not edit.
export const GEOM_KEYS = ${JSON.stringify(g.geom)};
export const COLOUR_KEYS = ${JSON.stringify(g.colour)};
export function __perturb(p: Record<string, unknown>): void {
${all.map((k) => `  if (p.${k} !== undefined) ${k} = p.${k} as never;`).join("\n")}
}
export function __defaults(): Record<string, unknown> {
  return { ${all.join(", ")} };
}
`;
writeFileSync(dst, s);
console.log(`wrote ${dst} — ${g.geom.length} geometry knobs, ${g.colour.length} colour knobs`);
